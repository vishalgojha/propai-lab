select null, 'locality', 'locality_reference', id from public.locality_reference
order by updated_at desc nulls last, id desc limit 500
on conflict (source_table, source_id) do nothing;
insert into public.semantic_embedding_jobs
  (tenant_id, entity_type, source_table, source_id)
select tenant_id, 'broker', 'brokers', id from public.brokers
order by updated_at desc nulls last, id desc limit 500
on conflict (source_table, source_id) do nothing;
