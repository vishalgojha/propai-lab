  r.broker_phone,
  null::text,
  coalesce(r.carpet_area_sqft, r.built_up_area_sqft, r.chargeable_area_sqft, r.saleable_area_sqft),
  case
    when r.price_per_sqft is not null and coalesce(r.carpet_area_sqft, r.built_up_area_sqft, r.chargeable_area_sqft, r.saleable_area_sqft) is not null
