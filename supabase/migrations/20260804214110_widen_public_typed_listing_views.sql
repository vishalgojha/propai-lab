  r.corrected_fields,
  r.correction_confidence,
  r.corrected_at,
  r.created_at,
  coalesce(r.updated_at, r.created_at),
  r.created_at,
  coalesce(r.updated_at, r.created_at),
  1::bigint,
  1::bigint,
  r.raw_message_id,
  r.raw_message_id,
  r.listing_index,
  nullif(trim(both '-' from regexp_replace(lower(coalesce(r.micro_market, r.locality_resolved, r.locality_raw, '')), '[^a-z0-9]+', '-', 'g')), ''),
  r.price_raw_text,
  r.price_qualifier,
  r.carpet_area_sqft,
  r.built_up_area_sqft,
  r.listing_index,
  r.source_fingerprint,
  'commercial'::text,
  'commercial'::text,
  'SELL'::text,
  'sale'::text,
  r.transaction_nature,
  r.broker_id
from public.commercial_sale_listings r

