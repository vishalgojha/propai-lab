  r.bhk::text,
  coalesce(r.carpet_area_sqft, r.built_up_area_sqft),
  case
    when r.rent_per_sqft is not null and coalesce(r.carpet_area_sqft, r.built_up_area_sqft) is not null
      then r.rent_per_sqft * coalesce(r.carpet_area_sqft, r.built_up_area_sqft)
    else r.monthly_rent
  end,
  'abs'::text,
  case when r.rent_per_sqft is not null then 'psf' else 'per_month' end::text,
  r.rent_per_sqft,
  r.furnishing_status,
  r.furnishing_status,
  null::text,
  r.floor_range,
  r.property_view,
  r.property_view,
  coalesce(r.locality_raw, r.locality_resolved, r.micro_market),
  r.locality_raw,
  r.locality_resolved,
  r.locality_confidence,
  r.landmark_name,
  r.street_name,
  r.group_name,
  r.summary_title,
  r.normalized_message,
  coalesce(r.raw_payload ->> 'full_text', r.normalized_message),
  coalesce(r.broker_name, r.broker_phone),
  r.raw_payload,
  r.ai_extraction,
  r.deal_tags,
  r.additional_charges,
  r.validation_flags,
  r.needs_review,
  r.extraction_confidence,
  r.corrected_fields,
  r.correction_confidence,
  r.corrected_at,
  r.created_at,
  coalesce(r.updated_at, r.created_at),
  r.created_at,
  coalesce(r.updated_at, r.created_at),
  1::bigint,
  1::bigint,
  r.raw_message_id,
  r.raw_message_id,
  r.listing_index,
  nullif(trim(both '-' from regexp_replace(lower(coalesce(r.micro_market, r.locality_resolved, r.locality_raw, '')), '[^a-z0-9]+', '-', 'g')), ''),
  r.price_raw_text,
  r.price_qualifier,
  r.carpet_area_sqft,
  r.built_up_area_sqft,
  r.listing_index,
  r.source_fingerprint,
  'residential'::text,
  'residential'::text,
  'RENT'::text,
  'rent'::text,
  null::text,
  r.broker_id
from public.residential_rent_listings r

