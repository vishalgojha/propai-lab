    else r.total_asking_price
  end,
  'abs'::text,
  case when r.price_per_sqft is not null then 'psf' else 'one_time' end::text,
  r.price_per_sqft,
  r.fitout_status,
  null::text,
  r.fitout_status,
  coalesce(r.floor_level, r.floor_range),
