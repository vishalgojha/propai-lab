  coalesce(r.carpet_area_sqft, r.built_up_area_sqft, r.chargeable_area_sqft),
  case
    when r.rent_per_sqft is not null and coalesce(r.carpet_area_sqft, r.built_up_area_sqft, r.chargeable_area_sqft) is not null
