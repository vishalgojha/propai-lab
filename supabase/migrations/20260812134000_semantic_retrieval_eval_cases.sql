-- Human-labelled retrieval cases turn semantic search from an infrastructure
-- metric into a measurable product-quality metric.
create table if not exists public.semantic_retrieval_eval_cases (
  id bigint generated by default as identity primary key,
  tenant_id uuid references public.organizations(id),
  query text not null check (length(btrim(query)) between 2 and 500),
  entity_type text not null check (entity_type in (
    'listing', 'requirement', 'building', 'building_alias',
    'locality', 'broker', 'broker_alias'
  )),
  source_table text not null,
  source_id bigint not null,
  top_k integer not null default 5 check (top_k between 1 and 20),
  active boolean not null default true,
  last_status text not null default 'never_run' check (last_status in ('never_run', 'passed', 'failed', 'error')),
  last_rank integer,
  last_similarity real,
  last_model text,
  last_error text,
  last_run_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant_id, query, source_table, source_id)
);

create index if not exists semantic_retrieval_eval_active_idx
  on public.semantic_retrieval_eval_cases (active, id);

alter table public.semantic_retrieval_eval_cases enable row level security;
revoke all on public.semantic_retrieval_eval_cases from anon, authenticated;
grant all on public.semantic_retrieval_eval_cases to service_role;
