-- Persist aggregate retrieval metrics so quality survives page refreshes.
create table if not exists public.semantic_retrieval_eval_runs (
  id bigint generated by default as identity primary key,
  model text not null,
  summary jsonb not null,
  created_at timestamptz not null default now()
);

create index if not exists semantic_retrieval_eval_runs_created_idx
  on public.semantic_retrieval_eval_runs (created_at desc, id desc);

alter table public.semantic_retrieval_eval_runs enable row level security;
revoke all on public.semantic_retrieval_eval_runs from anon, authenticated;
grant all on public.semantic_retrieval_eval_runs to service_role;
