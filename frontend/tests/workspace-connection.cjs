const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const file = require('node:path').join(__dirname, '../src/lib/workspaceConnection.ts');
const mod = {exports:{}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports:mod.exports,module:mod});
const {confirmedConnection:c,workspaceConnection:w,identityOnlyPhones:identity}=mod.exports;
let checks=0; const eq=(actual,expected)=>{assert.equal(actual,expected);checks++};
for(const state of ['unavailable','unknown','checking','error','']) eq(c({state,connected:false}),null);
for(const state of ['closed','disconnected','stopped','logged_out','loggedout','connecting','qr','pairing']) eq(c({state,connected:false}),false);
for(const state of ['connected','open']) eq(c({state}),true);
eq(c({state:'open',connected:true,status_stale:true}),null);
eq(c({state:'stopped',connected:false,status_stale:true}),null);
eq(c(null),null); eq(c({connected:false}),null);
const open={connection_state:'open',connected:true,live_status_available:true};
const closed={connection_state:'stopped',connected:false,live_status_available:true};
eq(w([open],{state:'unavailable',connected:false}),true);
eq(w([closed],{state:'open',connected:true}),true);
eq(w([closed],null),false);
eq(w([closed,{live_status_available:false}],null),null);
eq(w(identity([closed]),null),null);
eq(w(identity([open]),null),null);
eq(w([],{state:'unavailable',connected:false}),null);
eq(w([closed],{state:'unavailable',connected:false}),false);
eq(w([closed],{state:'stopped',connected:false}),false);
eq(w([open],{state:'stopped',connected:false}),true);
for(const state of ['open','connected']) eq(c({state,connected:false}),null);
for(const state of ['stopped','closed','disconnected']) eq(c({state,connected:true}),null);
const contradictoryOpen={...open,connected:false};
const contradictoryClosed={...closed,connected:true};
for(const conflict of [contradictoryOpen,contradictoryClosed]) {
 eq(w([conflict],null),null);
 eq(w([conflict],{state:'open',connected:false}),null);
 eq(w([conflict],{state:'open',connected:true}),true);
 eq(w([conflict],{state:'stopped',connected:false}),false);
}
eq(w([open],{state:'stopped',connected:true}),true);
eq(w([closed],{state:'open',connected:false}),false);
console.log(`${checks} workspace connection checks passed`);
